#!/usr/bin/env python3
"""Finite macOS AWDL-only TCP sender for an explicitly selected test peer.

Sends generated bytes, never reads user files. It complements AirDrop testing;
it does not reproduce AirDrop's application protocol or socket configuration.
"""
import argparse
import json
from pathlib import Path
import select
import socket
import struct
import time


def info(conn):
    raw = conn.getsockopt(socket.IPPROTO_TCP, 0x106, 256)
    if len(raw) < 112:
        raise RuntimeError('Unexpected Darwin TCP_CONNECTION_INFO size')
    return dict(cwnd=struct.unpack_from('=I', raw, 24)[0],
                snd_window=struct.unpack_from('=I', raw, 28)[0],
                srtt_ms=struct.unpack_from('=I', raw, 44)[0],
                retransmit_bytes=struct.unpack_from('=Q', raw, 72)[0],
                retransmit_packets=struct.unpack_from('=Q', raw, 104)[0])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--address', required=True)
    peers = parser.add_mutually_exclusive_group(required=True)
    peers.add_argument('--peer')
    peers.add_argument('--peer-file', type=Path,
                       help='Host-controlled exact current phone IPv6 address')
    parser.add_argument('--seconds', type=int, default=1800)
    args = parser.parse_args()
    if not 1 <= args.seconds <= 3600:
        parser.error('seconds must be between 1 and 3600')
    index = socket.if_nametoindex('awdl0')
    server = socket.socket(socket.AF_INET6, socket.SOCK_STREAM)
    server.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    server.setsockopt(socket.SOL_SOCKET, 0x1104, 1)  # SO_RECV_ANYIF on Darwin
    server.setsockopt(socket.IPPROTO_IPV6, 125, index)  # IPV6_BOUND_IF
    server.bind((args.address, 18773, 0, index))
    server.listen(2)
    server.settimeout(1)
    deadline = time.monotonic() + args.seconds
    block = b'\xa5' * 65536
    print('AWDL_BENCH_READY', flush=True)
    while time.monotonic() < deadline:
        try:
            conn, peer = server.accept()
        except socket.timeout:
            continue
        with conn:
            expected = args.peer_file.read_text().strip() if args.peer_file else args.peer
            if peer[0] != expected:
                continue
            conn.settimeout(5)
            request = b''
            try:
                while len(request) < 80 and not request.endswith(b'\n'):
                    part = conn.recv(1)
                    if not part:
                        break
                    request += part
                prefix, size = request.decode().strip().split()
                size = int(size)
                if prefix != 'OPAIRSHARE-BENCH-v1' or not 1024 <= size <= 32*1024*1024:
                    continue
                conn.setblocking(False)
                start = last = time.monotonic()
                sent = 0
                while sent < size and time.monotonic() < min(deadline, start+180):
                    _, writable, _ = select.select([], [conn], [], 0.2)
                    if writable:
                        try:
                            sent += conn.send(block[:min(len(block), size-sent)])
                        except BlockingIOError:
                            pass
                    if time.monotonic()-last >= 1:
                        print(json.dumps(dict(event='sample', epoch=time.time(),
                                              sent=sent, elapsed=time.monotonic()-start,
                                              **info(conn))), flush=True)
                        last = time.monotonic()
                conn.settimeout(10)
                verified = conn.recv(1) == b'K' if sent == size else False
                print(json.dumps(dict(event='done', sent=sent, verified=verified,
                                      elapsed=time.monotonic()-start, **info(conn))), flush=True)
            except (OSError, ValueError) as error:
                print(json.dumps(dict(event='error', error=str(error))), flush=True)


if __name__ == '__main__':
    main()
